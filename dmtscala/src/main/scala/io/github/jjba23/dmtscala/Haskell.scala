package io.github.jjba23.dmtscala

object Haskell {

  val serialize: Seq[Haskell.Record] => String = xs =>
    Seq(
      "-- auto-generated data classes",
      "-- do not edit this file manually",
      "-- output of dmtscala:",
      "--",
      "{-# LANGUAGE TemplateHaskell #-}",
      "{-# LANGUAGE OverloadedStrings #-}",
      "",
      "import Optics"
    ).mkString("\n") + "\n\n" +
      xs.map(_.toString).mkString("\n\n")

  private val typMap: Map[String, String] = Map.from(
    Seq(
      "String"  -> "String",
      "Instant" -> "ZonedTime",
      "Int"     -> "Int",
      "Long"    -> "Int",
      "Double"  -> "Double",
      "Boolean" -> "Bool"
    )
  )

  val toHaskellType: String => String = x => {
    val isOptional: Boolean    = x.startsWith("Option[")
    val optionalPrefix: String = if (isOptional) "Maybe " else ""
    val fromOption: String     =
      if (isOptional) x.drop(7).dropRight(1) else x

    val isSeq: Boolean  = fromOption.startsWith("Seq[")
    val fromSeq: String =
      if (isSeq) fromOption.drop(4).dropRight(1) else fromOption

    val isList: Boolean  = fromSeq.startsWith("List[")
    val fromList: String = if (isList) fromSeq.drop(5).dropRight(1) else fromSeq

    val listSuffix = if (isSeq || isList) "]" else ""
    val listPrefix = if (isSeq || isList) "[" else ""

    val typ = typMap.get(fromList).getOrElse(fromList)
    Seq(optionalPrefix, listPrefix, typ, listSuffix).mkString
  }

  val toHaskellName: String => String = x => {
    if (x.startsWith("`") && x.endsWith("`")) { x.drop(1).dropRight(1) }
    else x
  }

  case class Record(
    name: String,
    fields: Seq[ModelField],
    withDeriving: Option[String] = Some(
      " deriving (Eq, Show, Generic, FromJSON, ToJSON)"
    ),
    withLens: Boolean = true
  ) {

    override def toString: String = {
      val withLensS    = if (withLens) { s"\nmakeFieldLabelsNoPrefix ''$name\n" }
      else { "" }
      val mappedFields = fields
        .map(x => s"\t${toHaskellName(x.name)} :: ${toHaskellType(x.typ)},")
        .mkString("\n")
      s"""|data $name = $name{
    |$mappedFields
    |}${withDeriving.getOrElse("")}
    |${withLensS}""".stripMargin
    }
  }
}
