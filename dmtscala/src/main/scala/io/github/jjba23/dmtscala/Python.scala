package io.github.jjba23.dmtscala

object Python {

  val serialize: Seq[Python.DataClass] => String = xs =>
    Seq(
      "# auto-generated data classes",
      "# do not edit this file manually",
      "# output of dmtscala:",
      "#",
      "from marshmallow_dataclass import dataclass",
      "from typing import List, Optional"
    ).mkString("\n") + "\n\n" +
      xs.map(_.toString).mkString("\n\n")

  val typMap: Map[String, String] = Map.from(
    Seq(
      "String"  -> "str",
      "UUID"    -> "str",
      "Instant" -> "str",
      "Int"     -> "int",
      "Long"    -> "long",
      "Double"  -> "double",
      "Boolean" -> "bool"
    )
  )

  val toPythonType: String => String = x => {
    val isOptional: Boolean    = x.startsWith("Option[")
    val optionalPrefix: String = if (isOptional) "Optional[" else ""
    val optionalSuffix: String = if (isOptional) "]" else ""
    val fromOption: String     =
      if (isOptional) x.drop(7).dropRight(1) else x

    val isSeq: Boolean  = fromOption.startsWith("Seq[")
    val fromSeq: String =
      if (isSeq) fromOption.drop(4).dropRight(1) else fromOption

    val isList: Boolean  = fromSeq.startsWith("List[")
    val fromList: String = if (isList) fromSeq.drop(5).dropRight(1) else fromSeq

    val listSuffix = if (isSeq || isList) "]" else ""
    val listPrefix = if (isSeq || isList) "List[" else ""

    val typ = typMap.get(fromList).getOrElse(fromList)
    s"$optionalPrefix$listPrefix$typ$listSuffix$optionalSuffix"
  }

  val toPythonName: String => String = x => {
    if (x.startsWith("`") && x.endsWith("`")) { x.drop(1).dropRight(1) }
    else x
  }

  case class DataClass(name: String, fields: Seq[ModelField]) {

    override def toString: String = {
      val mappedFields = fields
        .map(x => s"\t${toPythonName(x.name)}:${toPythonType(x.typ)}")
        .mkString("\n")
      s"""|@dataclass
    |class $name:
    |$mappedFields
    """.stripMargin
    }
  }

}
